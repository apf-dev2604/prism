#!/usr/bin/env bash
# PRISM Raw DQ runner - five-argument handoff contract is unchanged.
set -Eeuo pipefail
umask 077
source "$HOME/scripts/prism/common/config/load_config.sh" || exit 1
BASE_DIR="$DIRECT2SILVER_PHASE"
PYTHON_BIN="$HOME/scripts/.venv/bin/python"
DQ_PY="${DQ_PY:-${BASE_DIR}/egms_gametx_dqraw.py}"
LOCK_FILE="${BASE_DIR}/work/egms_mysql_dlake_dq.lock"

FROM_DATE="${1:?Missing FROM_DATE}"
TO_DATE="${2:?Missing TO_DATE}"
JSONL_FILE="${3:?Missing JSONL_FILE}"
STARTED_FILE="${4:?Missing STARTED_FILE}"
STATUS_FILE="${5:?Missing STATUS_FILE}"

# One process-level error owner, including Python import/config/argument failures.
# Python keeps DQ logic and audit decisions, but does not send a duplicate email.
export PRISM_ALERT_OWNER=batch
mkdir -p "$BASE_LOG_DIR" "$(dirname "$STATUS_FILE")"
RUN_STAMP="$(date +%Y%m%d_%H%M%S)_$$"
RUN_LOG="$BASE_LOG_DIR/dqraw_${RUN_STAMP}.log"
ERROR_DETAIL="$BASE_LOG_DIR/dqraw_${RUN_STAMP}.traceback.log"

write_status() {
    local rc=$?
    trap - EXIT
    local result="FAIL"
    [[ "$rc" -eq 0 ]] && result="PASS"
    printf '%s\t%s\t%s\n' "$result" "$rc" "$(date -Is)" > "${STATUS_FILE}.tmp"
    mv -f "${STATUS_FILE}.tmp" "$STATUS_FILE"
    if [[ "$rc" -ne 0 ]]; then
        local error_summary
        if [[ -s "$ERROR_DETAIL" ]]; then
            error_summary=$("$PYTHON_BIN" "$SHARED_MODS/etl_report.py" --summarize-error "$ERROR_DETAIL" 2>/dev/null) || error_summary="DQ process error (inspect $ERROR_DETAIL)"
        else
            error_summary="Bash preflight or DQ execution failed; see ${RUN_LOG}"
        fi
        # Read the most recent Python traceback generated by this DQ execution.
        TRACEBACK_FILE="$(find "$BASE_LOG_DIR" -maxdepth 1 \
                -type f -name 'dqraw_*.traceback.log' \
                -printf '%T@ %p\n' 2>/dev/null \
                | sort -nr | head -1 | cut -d' ' -f2-)"

        ERROR_LOCATION=""
        ERROR_MESSAGE=""

        if [[ -n "$TRACEBACK_FILE" && -s "$TRACEBACK_FILE" ]]; then

        # Extract the final Python file and line number from the traceback.
           ERROR_LOCATION="$(sed -n \
                 's/^[[:space:]]*File "\([^"]*\)", line \([0-9][0-9]*\).*/\1:\2/p' \
                 "$TRACEBACK_FILE" | tail -1)"

       # Extract the actual exception, such as KeyError or RuntimeError.
           ERROR_MESSAGE="$(grep -E \
                '^[[:alnum:]_.]*(Error|Exception):' \
                "$TRACEBACK_FILE" | tail -1 || true)"
        fi

        [[ -n "$ERROR_LOCATION" ]] || ERROR_LOCATION="location unavailable"
        [[ -n "$ERROR_MESSAGE" ]] || ERROR_MESSAGE="Error details unavailable; check traceback log" 
        #printf '%s | ERROR | DQ RAW FAIL | rc=%s | %s\n' "$(date '+%Y-%m-%d %H:%M:%S')" "$rc" "$error_summary" | tee -a "$RUN_LOG" >&2
	printf '%s | ERROR | DQ RAW FAIL | rc=%s | %s | %s | traceback=%s\n' \
               "$(date '+%Y-%m-%d %H:%M:%S')" \
               "$rc" \
               "$ERROR_LOCATION" \
               "$ERROR_MESSAGE" \
               "${TRACEBACK_FILE:-unavailable}" >&2
        "$PYTHON_BIN" "$SHARED_MODS/etl_alert.py" \
            --stage MySQL-DLAKE-DQRAW --entity gameTransaction \
            --window-from "$FROM_DATE" --window-to "$TO_DATE" \
            --exit-code "$rc" --error-log "$RUN_LOG" || true
    fi
}
trap write_status EXIT

[[ -s "$JSONL_FILE" ]] || { echo "Missing JSONL input: $JSONL_FILE" | tee -a "$RUN_LOG" >&2; exit 2; }
[[ -f "$DQ_PY" ]] || { echo "DQ Python not found: $DQ_PY" | tee -a "$RUN_LOG" >&2; exit 2; }
mkdir -p "$(dirname "$LOCK_FILE")" "$(dirname "$STARTED_FILE")"
exec 9>"$LOCK_FILE"
flock -n 9 || { echo "DQ already running" | tee -a "$RUN_LOG" >&2; exit 75; }
printf 'DQ_START_REQUESTED\t%s\n' "$(date -Is)" > "$STARTED_FILE"

# Normal progress is visible and logged. Python stderr (unhandled traceback)
# goes to diagnostics, not the screen; EXIT trap reports concise actionable error.
"$PYTHON_BIN" "$DQ_PY" --from "$FROM_DATE" --to "$TO_DATE" \
    2> "$ERROR_DETAIL" | tee -a "$RUN_LOG"
echo "DQ FINAL PASS: $FROM_DATE" | tee -a "$RUN_LOG"

